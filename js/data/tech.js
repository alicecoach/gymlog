  const MACHINE_LOADS = ['plates', 'stack'];
  // Pasos para un ejercicio del catálogo o creado por la persona (si es máquina, por su patrón).
  function steps(ex) {
    if (!ex) return null;
    const own = X[ex.id];
    if (own) return own;
    const gen = MACHINE_LOADS.includes(ex.load) && BY_PATTERN[ex.pattern];
    if (!gen) return null;
    return ex.unilateral && ex.pattern !== 'squat' ? gen.concat('Se puede hacer con un lado cada vez.') : gen;
  }
  return { steps, has: ex => !!steps(ex) };
